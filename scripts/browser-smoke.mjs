async function clean() {
  for (const guest of guestIds) {
    await db.execute(sql`delete from wishlist_items where owner_id = ${guest}`);
    await db.execute(sql`delete from cart_items where owner_id = ${guest}`);
    await db.execute(sql`delete from addresses where owner_id = ${guest}`);
  }
  await db.execute(sql`update products set stock = stock + 1 where id = 'oslo-3-seater-sofa' and exists (select 1 from orders where email = ${email})`);
  await db.execute(sql`delete from orders where email = ${email}`);
  await db.execute(sql`delete from subscribers where email = ${email}`);
  await db.execute(sql`delete from messages where email = ${email}`);
}
